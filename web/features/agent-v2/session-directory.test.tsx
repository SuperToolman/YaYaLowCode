import { act, cleanup, renderHook, waitFor } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { useSessionDirectory } from "./session-directory";
import { listSessions } from "./client";
vi.mock("./client", () => ({ listSessions: vi.fn() }));
vi.mock("@/shared/lib/notify", () => ({ notifyRequestError: vi.fn() }));
afterEach(() => { cleanup(); vi.clearAllMocks(); vi.useRealTimers(); });
const page = { items: [], next_cursor: null };
it("joins slow background refreshes and accepts their result without showing initial loading again", async () => {
  vi.mocked(listSessions).mockResolvedValueOnce(page);
  const { result } = renderHook(() => useSessionDirectory(true, "", true));
  await waitFor(() => expect(listSessions).toHaveBeenCalledTimes(1));
  await waitFor(() => expect(result.current.loadingSessions).toBe(false));
  let finish!: (value: Awaited<ReturnType<typeof listSessions>>) => void;
  vi.mocked(listSessions).mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
  let first!: Promise<void>; let second!: Promise<void>;
  act(() => { first = result.current.refreshDirectory({ background: true }); });
  act(() => { second = result.current.refreshDirectory({ background: true }); });
  expect(first).toBe(second);
  expect(listSessions).toHaveBeenCalledTimes(2);
  expect(result.current.loadingSessions).toBe(false);
  expect(result.current.refreshingSessions).toBe(true);
  await act(async () => { finish(page); await first; });
  expect(result.current.refreshingSessions).toBe(false);
});
it("manual refresh replaces an older request so acknowledged actions can fetch fresh state", async () => {
  vi.mocked(listSessions).mockResolvedValueOnce(page);
  const { result } = renderHook(() => useSessionDirectory(true, "", true));
  await waitFor(() => expect(listSessions).toHaveBeenCalledTimes(1));
  await waitFor(() => expect(result.current.loadingSessions).toBe(false));
  let signal: AbortSignal | undefined;
  vi.mocked(listSessions).mockImplementationOnce((value) => { signal=value; return new Promise((_resolve,reject) => value?.addEventListener("abort", () => reject(new Error("aborted")))); });
  let older!: Promise<void>;
  act(() => { older = result.current.refreshDirectory({background:true}); });
  vi.mocked(listSessions).mockResolvedValueOnce(page);
  await act(async () => { await result.current.refreshDirectory(); await older; });
  expect(signal?.aborted).toBe(true);
  expect(result.current.sessionDirectoryError).toBe(false);
});
it("ends the loading state on timeout and exposes a retryable error", async () => {
  vi.useFakeTimers();
  vi.mocked(listSessions).mockImplementationOnce((signal) => new Promise((_resolve,reject) => signal?.addEventListener("abort", () => reject(new Error("timeout")))));
  const { result } = renderHook(() => useSessionDirectory(true,"",true));
  await act(async () => { await Promise.resolve(); });
  expect(result.current.loadingSessions).toBe(true);
  await act(async () => { await vi.advanceTimersByTimeAsync(15000); });
  expect(result.current.loadingSessions).toBe(false);
  expect(result.current.sessionDirectoryError).toBe(true);
});
