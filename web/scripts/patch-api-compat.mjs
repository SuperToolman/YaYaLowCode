import fs from "node:fs";

const indexPath = new URL("../app/lib/api-client/index.ts", import.meta.url);
const typesPath = new URL("../app/lib/api-client/types.gen.ts", import.meta.url);
let source = fs.readFileSync(indexPath, "utf8");
const generatedTypes = fs.readFileSync(typesPath, "utf8");
const aliases = [
  ["ApiApp", "App"],
  ["ApiAutomationFlow", "AutomationFlow"],
  ["ApiAutomationFlowList", "AutomationFlowList"],
  ["ApiFormSummary", "FormSummary"],
  ["ApiNavigationItem", "NavigationItem"],
].filter(([, alias]) => !generatedTypes.includes(`export type ${alias} =`));

source = source.replace(/\n\/\/ Compatibility aliases for application modules using the pre-HeyAPI names\.\nexport type \{[^\n]+\} from '\.\/types\.gen';\n/, "\n");
source = source.replace(/\nimport \{ controlledFetch \} from '\.\.\/api-request';\nimport \{ client \} from '\.\/client\.gen';\n\nclient\.setConfig\(\{ fetch: controlledFetch \}\);\n/, "\n");
source = source.replace(
  "// This file is auto-generated by @hey-api/openapi-ts",
  "// This file is auto-generated by @hey-api/openapi-ts\nimport { controlledFetch } from '../api-request';\nimport { client } from './client.gen';\n\nclient.setConfig({ fetch: controlledFetch });",
);
if (aliases.length > 0) {
  const aliasExports = aliases.map(([type, alias]) => `${type} as ${alias}`).join(", ");
  const block = `\n// Compatibility aliases for application modules using the pre-HeyAPI names.\nexport type { ${aliasExports} } from './types.gen';\n`;
  source = source.replace("// This file is auto-generated by @hey-api/openapi-ts", "// This file is auto-generated by @hey-api/openapi-ts" + block);
}
fs.writeFileSync(indexPath, source);
